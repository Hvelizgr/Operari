function eventLine(event: EventRow, data: TimelineData, t: (typeof STRINGS)['en']): string | null {
  const payload = (event.payload ?? {}) as Record<string, unknown>;
  const actor = inline(data.actorName(event.actorId));
  const comment = payload.comment ? `: ${inline(scrubString(String(payload.comment)))}` : '';
  switch (event.type) {
    case 'approval.requested':
      return `${t.approvalRequested}: ${inline(scrubString(String(payload.message ?? '')))}`;
    case 'approval.notified':
      return t.approvalNotified;
    case 'approval.escalated':
      return t.approvalEscalated;
    case 'approval.granted':
      return `${t.approvalGranted} ${actor}${comment}`;
    case 'approval.rejected':
      return `${t.approvalRejected} ${actor}${comment}`;
    case 'approval.expired':
      return t.approvalExpired;
    case 'run.paused':
      return t.paused;
    case 'run.resumed':
      return `${t.resumed} ${t.by} ${actor}`;
    case 'run.cancelled':
      return `${t.cancelled} ${t.by} ${actor}`;
    case 'ssh.privileged':
      return `${t.privileged}: ${inline(scrubString(String(payload.command ?? '')))}`;
    default:
      return null;
  }
}

export function renderIncidentTimeline(data: TimelineData, lang: TimelineLang): string {
  const t = STRINGS[lang];
  const { run, steps, events } = data;
  const alert = (run.metadata as { alert?: Record<string, unknown> } | null)?.alert;
  const iso = (d: Date) => d.toISOString();

  const entries: Array<{ at: Date; order: number; text: string }> = [];
  const add = (at: Date, text: string) => entries.push({ at, order: entries.length, text });

  if (alert?.startsAt) add(new Date(String(alert.startsAt)), t.alertFired);
  add(run.startedAt, t.runStarted);
  for (const step of steps) {
    const at = step.completedAt ?? step.startedAt;
    const error = step.error ? `: ${inline(scrubString(step.error))}` : '';
    add(
      at,
      `${t.step} ${inline(step.nodeName)} (${inline(step.nodeType)}): ${step.status}${error}`
    );
  }
  for (const event of events) {
    const text = eventLine(event, data, t);
    if (text) add(event.createdAt, text);
  }
  if (run.completedAt) add(run.completedAt, `${t.runEnded}: ${run.status}`);
  if (alert?.resolvedAt) add(new Date(String(alert.resolvedAt)), t.alertCleared);
  entries.sort((a, b) => a.at.getTime() - b.at.getTime() || a.order - b.order);

  const lines: string[] = [
    `# ${t.title}: ${inline(run.runbook.name)}`,
    '',
    `> ${t.warning}`,
    '',
    `- **${t.run}:** ${run.id}`,
    `- **${t.runbook}:** ${inline(run.runbook.slug ?? run.runbook.name)}`,
    `- **${t.status}:** ${run.status}`,
    `- **${t.trigger}:** ${run.trigger}`,
    `- **${t.started}:** ${iso(run.startedAt)}`,
    `- **${t.finished}:** ${run.completedAt ? iso(run.completedAt) : t.notFinished}`,
  ];
  if (run.duration != null) lines.push(`- **${t.duration}:** ${run.duration} ms`);
  if (run.error) lines.push(`- **Error:** ${inline(scrubString(run.error))}`);
  if (run.dryRun) lines.push('', t.dryRun);

  if (alert) {
    lines.push('', `## ${t.alert}`, '', `- **${t.alert}:** ${inline(alert.name)}`);
    lines.push(`- **${t.source}:** ${inline(alert.source)}`);
    if (alert.severity) lines.push(`- **${t.severity}:** ${inline(alert.severity)}`);
    if (alert.startsAt) lines.push(`- **${t.firing}:** ${inline(alert.startsAt)}`);
    lines.push(
      `- **${t.resolved}:** ${alert.resolvedAt ? inline(alert.resolvedAt) : t.stillFiring}`
    );
  }

  lines.push('', `## ${t.timeline}`, '');
  for (const entry of entries) lines.push(`- \`${iso(entry.at)}\` ${entry.text}`);

  const shown = steps.filter(step => step.nodeType !== 'approval').slice(0, MAX_OUTPUT_STEPS);
  const omitted = steps.filter(step => step.nodeType !== 'approval').length - shown.length;
  lines.push('', `## ${t.outputs}`);
  for (const step of shown) {
    lines.push('', `### ${inline(step.nodeName)}`, '');
    if (step.output === null || step.output === undefined) {
      lines.push(t.noOutput);
      continue;
    }
    const scrubbed = scrubOutput(step.output);
    const text = typeof scrubbed === 'string' ? scrubbed : JSON.stringify(scrubbed, null, 2);
    const clipped =
      text.length > MAX_OUTPUT_CHARS ? `${text.slice(0, MAX_OUTPUT_CHARS)}\n[…]` : text;
    lines.push(fenced(clipped));
  }
  if (omitted > 0) lines.push('', `${omitted} ${t.outputsOmitted}`);

  lines.push('', `## ${t.evidence}`, '', t.evidenceHint, '');
  for (const event of events) {
    lines.push(`- #${event.seq} \`${iso(event.createdAt)}\` ${event.type} \`${event.hash}\``);
  }
  if (data.eventsTruncated) lines.push('', t.eventsTruncated);

  lines.push('', `## ${t.postmortem}`, '', `### ${t.impact}`, '', `### ${t.rootCause}`, '');
  lines.push(`### ${t.followUps}`, '');
  return lines.join('\n');
}

export async function loadIncidentTimeline(
  prisma: PrismaClient,
  tenantId: string,
  runId: string
): Promise<TimelineData | null> {
  const run = await prisma.execution.findFirst({
    where: { id: runId, runbook: { tenantId } },
    include: {
      runbook: { select: { slug: true, name: true } },
      nodeLogs: { orderBy: { startedAt: 'asc' } },
    },
  });
  if (!run) return null;

  const rows = await prisma.auditEvent.findMany({
    where: {
      tenantId,
      createdAt: { gte: new Date(run.startedAt.getTime() - 60_000) },
      OR: [
        { resource: runId },
        { actorId: `run:${runId}` },
        { payload: { path: ['executionId'], equals: runId } },
      ],
    },
    orderBy: { seq: 'asc' },
    take: MAX_EVENTS + 1,
    select: { seq: true, type: true, actorId: true, payload: true, hash: true, createdAt: true },
  });
  const events = rows.slice(0, MAX_EVENTS);

  const bareId = (actorId: string) => actorId.replace(/^user:/, '');
  const ids = Array.from(new Set(events.flatMap(e => (e.actorId ? [bareId(e.actorId)] : []))));
  const users = ids.length
    ? await prisma.user.findMany({
        where: { id: { in: ids }, tenantId },
        select: { id: true, email: true },
      })
    : [];
  const emails = new Map(users.map(user => [user.id, user.email]));
  const deleted = await buildDeletedActorSet(new AuditService(prisma), tenantId);

  const actorName = (actorId: string | null): string => {
    if (!actorId) return 'system';
    if (actorId.startsWith('apikey:')) return `API key ${actorId.slice('apikey:'.length)}`;
    const id = bareId(actorId);
    if (deleted.has(id)) return maskDeletedId(id);
    return emails.get(id) ?? id;
  };

  return {
    run: { ...run, trigger: String(run.trigger), status: String(run.status) },
    steps: run.nodeLogs.map(log => ({ ...log, status: String(log.status) })),
    events,
    eventsTruncated: rows.length > MAX_EVENTS,
    actorName,
  };
}
