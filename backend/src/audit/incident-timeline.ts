const MAX_EVENTS = 500;
const MAX_OUTPUT_STEPS = 40;
const MAX_OUTPUT_CHARS = 1000;

export type TimelineLang = 'en' | 'es';

interface StepRow {
  nodeName: string;
  nodeType: string;
  status: string;
  startedAt: Date;
  completedAt: Date | null;
  duration: number | null;
  output: unknown;
  error: string | null;
}

interface EventRow {
  seq: bigint;
  type: string;
  actorId: string | null;
  payload: unknown;
  hash: string;
  createdAt: Date;
}

export interface TimelineData {
  run: {
    id: string;
    status: string;
    trigger: string;
    startedAt: Date;
    completedAt: Date | null;
    duration: number | null;
    error: string | null;
    dryRun: boolean;
    metadata: unknown;
    runbook: { slug: string | null; name: string };
  };
  steps: StepRow[];
  events: EventRow[];
  eventsTruncated: boolean;
  actorName: (actorId: string | null) => string;
}

const SENSITIVE_KEY =
  /pass(word|wd)?|secret|token|api[-_]?key|authorization|cookie|private[-_]?key|credential/i;
const SENSITIVE_VALUE: RegExp[] = [
  /\b(Bearer|Basic)\s+[A-Za-z0-9._~+/=-]{8,}/gi,
  /\b(sk|pk|rk)-[A-Za-z0-9_-]{16,}/g,
  /\bgh[pousr]_[A-Za-z0-9]{20,}/g,
  /\bxox[a-z]-[A-Za-z0-9-]{10,}/g,
  /\bAKIA[0-9A-Z]{16}\b/g,
  /\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]+/g,
  /hooks\.slack\.com\/services\/\S+/g,
  /-----BEGIN [A-Z ]*PRIVATE KEY-----[\s\S]*?(-----END [A-Z ]*PRIVATE KEY-----|$)/g,
];
const MASK = '[redacted]';

function scrubString(value: string): string {
  const masked = SENSITIVE_VALUE.reduce((text, re) => text.replace(re, MASK), value);
  return masked
    .replace(/(:\/\/[^\s:/@]+:)[^\s@/]+@/g, `$1${MASK}@`)
    .replace(
      /\b([A-Za-z_][A-Za-z0-9_-]*(?:pass(?:word|wd)?|secret|token|api[-_]?key)[A-Za-z0-9_-]*)(\s*[=:]\s*)\S+/gi,
      `$1$2${MASK}`
    );
}

/** Best effort: secrets are only known by shape, so the export tells readers to review it. */
export function scrubOutput(value: unknown): unknown {
  if (typeof value === 'string') return scrubString(value);
  if (Array.isArray(value)) return value.map(scrubOutput);
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [
        key,
        SENSITIVE_KEY.test(key) && item !== null ? MASK : scrubOutput(item),
      ])
    );
  }
  return value;
}

/** User text lands in documents people paste elsewhere: it must stay plain text. */
export function inline(value: unknown): string {
  return String(value ?? '')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/([\\`*_[\]<>|#~])/g, '\\$1');
}

function fenced(text: string): string {
  const longest = Math.max(0, ...(text.match(/`+/g) ?? []).map(run => run.length));
  const fence = '`'.repeat(Math.max(3, longest + 1));
  return `${fence}text\n${text}\n${fence}`;
}

