function translateCore(core: string): string | null {
  if (EXACT[core]) return EXACT[core];
  for (const [re, build] of PATTERNS) {
    const m = core.match(re);
    if (!m) continue;
    const noun = NOUNS[m[1].toLowerCase()];
    if (noun) return build(noun);
  }
  return null;
}

/** The label to show for a field whose definition gives `en`. */
export function fieldLabel(en: string, lang: Lang): string {
  if (lang !== 'es' || !en) return en;
  const m = en.match(/^(.*?)\s*\(([^()]*)\)$/);
  const core = m ? m[1] : en;
  const translated = translateCore(core);
  if (!translated) return en;
  if (!m) return translated;
  return `${translated} (${SUFFIXES[m[2]] ?? m[2]})`;
}

/** The name to show for a select option that may carry its own Spanish name. */
export function optionLabel(option: { name: string; es?: string }, lang: Lang): string {
  return lang === 'es' && option.es ? option.es : option.name;
}
