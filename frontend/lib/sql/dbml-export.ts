import { formatColumnType, type GroupedMetadata, type SqlForeignKey } from './metadata';

/**
 * Render a `SqlMetadata` payload as a DBML document. DBML is the
 * de-facto-standard text format that dbdiagram.io / dbdocs.io and a
 * handful of internal-tooling teams use; surfacing it from the
 * Operari schema view lets a DBA hand the schema to those tools
 * without us having to host a parser.
 *
 * Spec reference: https://dbml.dbdiagram.io/docs/. We implement the
 * `Table`, `Indexes`, and `Ref` blocks — that's enough for round-trip
 * with the major consumers and matches what every DBML-aware tool
 * expects to see.
 *
 * Pure function, no I/O. Deterministic on the same metadata input
 * (we sort the inputs upstream in `groupMetadata`), which lets a
 * commit-to-Git workflow surface real schema diffs.
 */

const NEEDS_QUOTES_PATTERN = /[^a-zA-Z0-9_]/;

function quoteIdent(name: string): string {
  if (!NEEDS_QUOTES_PATTERN.test(name)) return name;
  return `"${name.replace(/"/g, '\\"')}"`;
}

function quoteString(value: string): string {
  return `'${value.replace(/'/g, "\\'")}'`;
}

function refTarget(schema: string, table: string, column: string): string {
  return `${quoteIdent(schema)}.${quoteIdent(table)}.${quoteIdent(column)}`;
}

function defaultExpr(value: string): string {
  // Backtick-wrap function calls and bare expressions so DBML treats
  // them as raw SQL. Numeric / boolean literals and quoted strings
  // pass through unchanged.
  const trimmed = value.trim();
  if (/^[+-]?\d+(\.\d+)?$/.test(trimmed)) return trimmed;
  if (/^(true|false|null)$/i.test(trimmed)) return trimmed.toLowerCase();
  if (/^'.*'$/.test(trimmed)) return trimmed;
  return `\`${trimmed}\``;
}

function renderColumn(col: {
  name: string;
  type: string;
  nullable: boolean;
  default: string | null;
  comment: string | null;
  isIdentity: boolean;
  isArray: boolean;
  characterMaximumLength: number | null;
  precision: number | null;
  scale: number | null;
}): string {
  const settings: string[] = [];
  if (!col.nullable) settings.push('not null');
  if (col.isIdentity) settings.push('increment');
  if (col.default != null) settings.push(`default: ${defaultExpr(col.default)}`);
  if (col.comment) settings.push(`note: ${quoteString(col.comment)}`);
  const typeStr = formatColumnType({
    ...col,
    schema: '',
    table: '',
    ordinalPosition: 0,
  });
  const settingsStr = settings.length > 0 ? ` [${settings.join(', ')}]` : '';
  return `  ${quoteIdent(col.name)} ${typeStr}${settingsStr}`;
}

function renderIndex(idx: {
  name: string;
  unique: boolean;
  type: string;
  isPrimary: boolean;
  columns: string[];
}): string {
  // Primary keys are rendered inline on the column when single-column,
  // otherwise as a composite `pk` index. dbdiagram convention.
  const settings: string[] = [];
  if (idx.isPrimary) settings.push('pk');
  else if (idx.unique) settings.push('unique');
  if (idx.type && idx.type !== 'btree') settings.push(`type: ${idx.type}`);
  settings.push(`name: ${quoteString(idx.name)}`);
  const cols = idx.columns.map(c => quoteIdent(c)).join(', ');
  const wrapped = idx.columns.length === 1 ? cols : `(${cols})`;
  return `    ${wrapped} [${settings.join(', ')}]`;
}

function cardinalityFor(fk: SqlForeignKey): string {
  // Without unique-constraint introspection we can't reliably tell
  // 1:1 from N:1, so we always emit `>` (many-to-one). DBML
  // consumers can adjust manually if needed; this matches what
  // every other generic-DBML exporter does today.
  void fk;
  return '>';
}

export interface DbmlExportOptions {
  /** Hidden if undefined — emit every schema. Otherwise restrict to
   *  this set. Useful for partial exports from a filtered diagram. */
  visibleSchemas?: ReadonlySet<string>;
  /** Database name written into the project header. Defaults to
   *  `db` so the resulting file imports cleanly into any consumer. */
  projectName?: string;
}

export function exportDbml(metadata: GroupedMetadata, options: DbmlExportOptions = {}): string {
  const { visibleSchemas, projectName = 'db' } = options;
  const visible = (schema: string): boolean => !visibleSchemas || visibleSchemas.has(schema);

  const lines: string[] = [];
  lines.push(`Project ${quoteIdent(projectName)} {`);
  lines.push(`  database_type: 'PostgreSQL'`);
  lines.push(`  Note: 'Generated by Operari'`);
  lines.push('}');
  lines.push('');

  for (const table of metadata.tables) {
    if (!visible(table.schema)) continue;
    if (table.isView || table.isMaterializedView) continue;

    const headerSettings: string[] = [];
    if (table.comment) headerSettings.push(`note: ${quoteString(table.comment)}`);
    const headerSettingsStr = headerSettings.length > 0 ? ` [${headerSettings.join(', ')}]` : '';
    lines.push(`Table ${quoteIdent(table.schema)}.${quoteIdent(table.name)}${headerSettingsStr} {`);
    for (const col of table.columns) {
      lines.push(renderColumn(col));
    }
    if (table.indexes.length > 0) {
      lines.push('');
      lines.push('  Indexes {');
      for (const idx of table.indexes) {
        lines.push(renderIndex(idx));
      }
      lines.push('  }');
    }
    lines.push('}');
    lines.push('');
  }

  // FK refs go at the bottom so they can reference tables declared
  // anywhere above. dbdiagram tolerates inline `[ref: > ...]` on the
  // column too, but a trailing block is easier to diff and review.
  const fks = metadata.foreignKeys.filter(fk => visible(fk.schema) && visible(fk.referencedSchema));
  if (fks.length > 0) {
    for (const fk of fks) {
      const card = cardinalityFor(fk);
      lines.push(
        `Ref ${quoteString(fk.constraintName)}: ` +
          `${refTarget(fk.schema, fk.table, fk.column)} ${card} ` +
          `${refTarget(fk.referencedSchema, fk.referencedTable, fk.referencedColumn)}` +
          (fk.onDelete ? ` [delete: ${fk.onDelete.toLowerCase()}]` : '')
      );
    }
    lines.push('');
  }

  return lines.join('\n');
}
